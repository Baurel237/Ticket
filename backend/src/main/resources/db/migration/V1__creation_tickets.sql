-- Schéma initial de l'application de tickets.
-- Compatible PostgreSQL et H2 (MODE=PostgreSQL, utilisé pour les tests).
-- La contrainte d'unicité est nommée (uk_titre) : le gestionnaire d'erreurs
-- fait correspondre le 409 RG-02 à ce nom, indépendamment du libellé du
-- driver JDBC.

CREATE TABLE tickets (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titre         VARCHAR(100)  NOT NULL,
    description   VARCHAR(2000),
    statut        VARCHAR(20)   NOT NULL,
    date_creation TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_titre UNIQUE (titre)
);
